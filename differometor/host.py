def _div(x, y):
    if np.issubdtype(np.result_type(x, y), np.integer):
        return np.trunc(np.divide(x, y)).astype(np.result_type(x, y))
    return np.divide(x, y)


def _select_n(which, *cases):
    if which.dtype == np.bool_:
        return np.where(which, cases[1], cases[0])
    return np.choose(which, cases)


_ELEMENTWISE = {
    "mul": np.multiply, "div": _div, "add": np.add, "add_any": np.add, "sub": np.subtract,
    "neg": np.negative, "exp": np.exp, "log": np.log, "sin": np.sin, "cos": np.cos, "tan": np.tan,
    "sinh": np.sinh, "cosh": np.cosh, "tanh": np.tanh, "sqrt": np.sqrt, "asin": np.arcsin,
    "acos": np.arccos, "atan": np.arctan, "atan2": np.arctan2, "conj": np.conj, "real": np.real,
    "imag": np.imag, "square": np.square, "abs": np.abs, "sign": np.sign, "log1p": np.log1p,
    "expm1": np.expm1, "pow": np.power, "max": np.maximum, "min": np.minimum,
    "eq": np.equal, "ne": np.not_equal, "lt": np.less, "le": np.less_equal, "gt": np.greater,
    "ge": np.greater_equal, "and": np.logical_and, "or": np.logical_or, "not": np.logical_not,
    "rsqrt": lambda x: 1.0 / np.sqrt(x), "complex": lambda re, im: re + 1j * im,
    "select_n": _select_n, "copy": lambda x: x, "copy_p": lambda x: x,
}

# Only transparent calls may be differentiated by recursively interpreting their
# primal body. Custom JVP/VJP calls carry separate derivative semantics; treating
# them as transparent would discard those rules. The coverage check rejects them
# and make_simulation_arrays selects the traced JAX path instead.
_CALL_PRIMITIVES = {"pjit", "jit", "closed_call", "core_call", "remat", "checkpoint"}


def _inner_jaxpr(params):
    for key in ("jaxpr", "call_jaxpr", "fun_jaxpr"):
        if key in params:
            inner = params[key]
            if hasattr(inner, "jaxpr"):
                return inner.jaxpr, [np.asarray(c) for c in inner.consts]
            return inner, []
    raise NotImplementedError("call primitive without a jaxpr")


def _apply(primitive: str, params: dict, args: list, nb: int):
    """Apply one primitive to NumPy arrays that all carry `nb` leading batch dimensions."""
    if primitive in _ELEMENTWISE:
        return _ELEMENTWISE[primitive](*args)
    x = args[0] if args else None
    if primitive == "integer_pow":
        return x ** params["y"]
    if primitive == "convert_element_type":
        return np.asarray(x).astype(np.dtype(params["new_dtype"]), copy=False)
    if primitive == "broadcast_in_dim":
        lead, shape, dims = x.shape[:nb], tuple(params["shape"]), params["broadcast_dimensions"]
        staged = [1] * len(shape)
        for source, target in enumerate(dims):
            staged[target] = x.shape[nb + source]
        return np.broadcast_to(x.reshape(lead + tuple(staged)), lead + shape)
    if primitive == "reshape":
        return x.reshape(x.shape[:nb] + tuple(params["new_sizes"]))
    if primitive == "squeeze":
        return np.squeeze(x, axis=tuple(nb + d for d in params["dimensions"]))
    if primitive == "expand_dims":
        return np.expand_dims(x, axis=tuple(nb + d for d in params["dimensions"]))
    if primitive == "slice":
        strides = params.get("strides") or [1] * len(params["start_indices"])
        index = tuple(slice(s, e, k) for s, e, k in zip(params["start_indices"], params["limit_indices"], strides))
        return x[(slice(None),) * nb + index]
    if primitive == "concatenate":
        lead = np.broadcast_shapes(*(a.shape[:nb] for a in args))
        parts = [np.broadcast_to(a, lead + a.shape[nb:]) for a in args]
        return np.concatenate(parts, axis=nb + params["dimension"])
    if primitive == "split":
        cuts = np.cumsum(params["sizes"])[:-1]
        return np.split(x, cuts, axis=nb + params["axis"])
    if primitive == "transpose":
        return np.transpose(x, tuple(range(nb)) + tuple(nb + p for p in params["permutation"]))
    if primitive == "iota":
        shape, dimension = tuple(params["shape"]), params["dimension"]
        ramp = np.arange(shape[dimension], dtype=np.dtype(params["dtype"]))
        ramp = ramp.reshape([-1 if d == dimension else 1 for d in range(len(shape))])
        return np.broadcast_to(ramp, shape).reshape((1,) * nb + shape)
    if primitive == "reduce_sum":
        return np.sum(x, axis=tuple(nb + a for a in params["axes"]))
    if primitive == "reduce_max":
        return np.max(x, axis=tuple(nb + a for a in params["axes"]))
    if primitive == "reduce_min":
        return np.min(x, axis=tuple(nb + a for a in params["axes"]))
    if primitive in _CALL_PRIMITIVES:
        inner, consts = _inner_jaxpr(params)
        return _evaluate_jaxpr(inner, consts, args, nb)
    raise NotImplementedError(f"primitive '{primitive}' is not supported by the NumPy interpreter")


def _evaluate_jaxpr(jaxpr, consts, args, nb: int):
    """Evaluate a jaxpr with NumPy. Inputs carry `nb` leading batch dimensions."""
    env = {}

    def read(v):
        if hasattr(v, "val"):  # Literal
            value = np.asarray(v.val)
            return value.reshape((1,) * nb + value.shape)
        return env[v]

    for var, value in zip(jaxpr.constvars, consts):
        value = np.asarray(value)
        env[var] = value.reshape((1,) * nb + value.shape)
    for var, value in zip(jaxpr.invars, args):
        env[var] = value
    for eqn in jaxpr.eqns:
        result = _apply(eqn.primitive.name, eqn.params, [read(v) for v in eqn.invars], nb)
        if eqn.primitive.multiple_results:
            for var, value in zip(eqn.outvars, result):
                env[var] = value
        else:
            env[eqn.outvars[0]] = result
    return [read(v) for v in jaxpr.outvars]


# Forward-mode (tangent) rules for the primitives that appear in component functions.
# Linear and structural primitives map tangents with the primitive itself.
_LINEAR = {"add", "add_any", "sub", "neg", "conj", "real", "imag", "complex", "convert_element_type",
           "broadcast_in_dim", "reshape", "squeeze", "expand_dims", "slice", "concatenate", "split",
           "transpose", "reduce_sum", "copy", "copy_p"}
_NON_DIFFERENTIABLE = {"eq", "ne", "lt", "le", "gt", "ge", "and", "or", "not", "sign", "iota",
                       "floor", "ceil", "round"}


def _zeros_like_primal(x, tangents):
    dtype = np.result_type(x, *[t for t in tangents if t is not None])
    return np.zeros(x.shape, dtype=dtype)


def _tangent(primitive: str, params: dict, xs: list, ts: list, outs: list, nb: int) -> list:
    """Output tangents of one primitive, given primal inputs `xs`, input tangents `ts` (None = zero)."""
    if primitive in _NON_DIFFERENTIABLE:
        return [None] * len(outs)
    if primitive in _LINEAR:
        if primitive in ("add", "add_any", "sub", "complex", "concatenate"):
            ts = [t if t is not None else _zeros_like_primal(x, ts) for x, t in zip(xs, ts)]
        result = _apply(primitive, params, ts, nb)
        return list(result) if isinstance(result, list) else [result]
    if primitive == "select_n":
        cases = [t if t is not None else _zeros_like_primal(x, ts[1:]) for x, t in zip(xs[1:], ts[1:])]
        return [_select_n(xs[0], *cases)]
    out = outs[0]
    if primitive == "mul":
        (x, y), (tx, ty) = xs, ts
        terms = ([tx * y] if tx is not None else []) + ([x * ty] if ty is not None else [])
        return [terms[0] + terms[1] if len(terms) == 2 else terms[0]]
    if primitive == "div":
        (x, y), (tx, ty) = xs, ts
        terms = ([tx / y] if tx is not None else []) + ([-(out * ty) / y] if ty is not None else [])
        return [terms[0] + terms[1] if len(terms) == 2 else terms[0]]
    if primitive == "pow":
        (x, y), (tx, ty) = xs, ts
        terms = ([tx * y * x ** (y - 1)] if tx is not None else []) + ([ty * np.log(x) * out] if ty is not None else [])
        return [terms[0] + terms[1] if len(terms) == 2 else terms[0]]
    if primitive in ("max", "min"):
        (x, y), (tx, ty) = xs, ts
        tx = tx if tx is not None else _zeros_like_primal(x, ts)
        ty = ty if ty is not None else _zeros_like_primal(y, ts)
        pick_x = (x > y) if primitive == "max" else (x < y)
        return [np.where(pick_x, tx, np.where(x == y, 0.5 * (tx + ty), ty))]
    (x,), (t,) = xs, ts
    if primitive == "integer_pow":
        y = params["y"]
        return [t * 0 if y == 0 else t * y * x ** (y - 1)]
    rules = {
        "exp": lambda: out * t, "log": lambda: t / x, "log1p": lambda: t / (1 + x), "expm1": lambda: (out + 1) * t,
        "sin": lambda: np.cos(x) * t, "cos": lambda: -np.sin(x) * t, "tan": lambda: t * (1 + out * out),
        "sinh": lambda: np.cosh(x) * t, "cosh": lambda: np.sinh(x) * t, "tanh": lambda: t * (1 - out * out),
        "sqrt": lambda: t / (2 * out), "rsqrt": lambda: -0.5 * out / x * t,
        "asin": lambda: t / np.sqrt(1 - x * x), "acos": lambda: -t / np.sqrt(1 - x * x),
        "atan": lambda: t / (1 + x * x), "square": lambda: 2 * x * t,
        # Match JAX 0.9's abs JVP: real +/-0 selects +t; complex zero
        # selects zero through a guarded denominator. np.sign(0) differs.
        "abs": lambda: (np.real(t * (np.conj(x) / np.where(out == 0, 1, out))))
        if np.iscomplexobj(x) else np.where(x >= 0, t, -t),
    }
    if primitive not in rules:
        raise NotImplementedError(f"no tangent rule for primitive '{primitive}'")
    with np.errstate(divide="ignore", invalid="ignore"):
        return [rules[primitive]()]


def _jvp_jaxpr(jaxpr, consts, primals, tangents, nb: int):
    """Forward-mode evaluation of a jaxpr with NumPy: (outputs, output tangents); None = zero tangent."""
    env, tangent_env = {}, {}

    def read(v):
        if hasattr(v, "val"):  # Literal
            value = np.asarray(v.val)
            return value.reshape((1,) * nb + value.shape)
        return env[v]

    def read_tangent(v):
        return None if hasattr(v, "val") else tangent_env.get(v)

    for var, value in zip(jaxpr.constvars, consts):
        value = np.asarray(value)
        env[var] = value.reshape((1,) * nb + value.shape)
    for var, value, tangent in zip(jaxpr.invars, primals, tangents):
        env[var], tangent_env[var] = value, tangent
    for eqn in jaxpr.eqns:
        name = eqn.primitive.name
        xs = [read(v) for v in eqn.invars]
        ts = [read_tangent(v) for v in eqn.invars]
        if name in _CALL_PRIMITIVES:
            inner, inner_consts = _inner_jaxpr(eqn.params)
            outs, out_tangents = _jvp_jaxpr(inner, inner_consts, xs, ts, nb)
        else:
            result = _apply(name, eqn.params, xs, nb)
            outs = list(result) if eqn.primitive.multiple_results else [result]
            out_tangents = [None] * len(outs) if all(t is None for t in ts) else _tangent(
                name, eqn.params, xs, ts, outs, nb)
        for var, value, tangent in zip(eqn.outvars, outs, out_tangents):
            env[var], tangent_env[var] = value, tangent
    return [read(v) for v in jaxpr.outvars], [read_tangent(v) for v in jaxpr.outvars]


_STRUCTURAL = {"integer_pow", "convert_element_type", "broadcast_in_dim", "reshape", "squeeze", "expand_dims",
               "slice", "concatenate", "split", "transpose", "iota", "reduce_sum", "reduce_max", "reduce_min"}
_TANGENT_RULES = {"mul", "div", "pow", "max", "min", "select_n", "integer_pow", "exp", "log", "log1p", "expm1",
                  "sin", "cos", "tan", "sinh", "cosh", "tanh", "sqrt", "rsqrt", "asin", "acos", "atan", "square",
                  "abs"}


def unsupported_primitives(jaxpr) -> set:
    """Primitives in `jaxpr` (recursively) that the NumPy interpreter cannot evaluate or differentiate."""
    missing = set()
    for eqn in jaxpr.eqns:
        name = eqn.primitive.name
        if name in _CALL_PRIMITIVES:
            missing |= unsupported_primitives(_inner_jaxpr(eqn.params)[0])
            continue
        evaluable = name in _ELEMENTWISE or name in _STRUCTURAL
        differentiable = name in _LINEAR or name in _NON_DIFFERENTIABLE or name in _TANGENT_RULES
        if not (evaluable and differentiable):
            missing.add(name)
    return missing


class JvpKernel:
    """
    Value and Jacobian of a component function `fn: R^shape -> C^out`, evaluated with NumPy.

    `fn` is traced once (forward only) into a jaxpr; `_jvp_jaxpr` evaluates it with
    forward-mode derivatives, batched over all entries and frequencies. Calling with x of
    shape (*B, *shape) returns (value (*B, *out), jacobian (n, *B, *out)).

    Raises NotImplementedError at construction if the function uses a primitive the
    interpreter does not support; the caller then falls back to the traced JAX path.
    """

    def __init__(self, fn, shape: tuple):
        closed = jax.make_jaxpr(fn)(jax.ShapeDtypeStruct(shape, jnp.float64))
        missing = unsupported_primitives(closed.jaxpr)
        if missing:
            raise NotImplementedError(f"{getattr(fn, '__name__', fn)} uses unsupported primitives {sorted(missing)}")
        self.jaxpr = closed.jaxpr
        self.consts = [np.asarray(c) for c in closed.consts]
        self.shape = tuple(shape)
        self.out_shape = tuple(closed.out_avals[0].shape)
        self.size = int(np.prod(shape)) if shape else 1

    def __call__(self, x: np.ndarray, slots=None):
        """
        Value and derivatives along the input slots `slots` (flat input indices).

        `slots=None` differentiates along every input; an empty sequence computes the
        value only. Returns (value (*B, *out), derivative (len(slots), *B, *out)).
        """
        batch = x.shape[: x.ndim - len(self.shape)]
        slots = np.arange(self.size) if slots is None else np.asarray(slots, dtype=int)
        # Batch dimensions: (tangent direction, *batch).
        primal = x.reshape((1,) + x.shape)
        tangent = None
        if len(slots):
            tangent = np.zeros((len(slots), self.size))
            tangent[np.arange(len(slots)), slots] = 1.0
            tangent = tangent.reshape((len(slots),) + (1,) * len(batch) + self.shape)
        (value,), (derivative,) = _jvp_jaxpr(self.jaxpr, self.consts, [primal], [tangent], 1 + len(batch))
        value = np.broadcast_to(value, (1,) + batch + self.out_shape)[0]
        if derivative is None:
            derivative = np.zeros((len(slots),) + batch + self.out_shape, dtype=value.dtype)
        derivative = np.broadcast_to(derivative, (len(slots),) + batch + self.out_shape)
        return value, derivative


_KERNELS: dict = {}


def kernel(fn, shape: tuple) -> JvpKernel:
    """Cached `JvpKernel` per (function, input shape)."""
    key = (fn, tuple(shape))
    if key not in _KERNELS:
        _KERNELS[key] = JvpKernel(fn, tuple(shape))
    return _KERNELS[key]


