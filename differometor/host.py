class _Stage:
    """
    Component-function groups of one stage, with entry Jacobians.

    Jacobian modes: "full" differentiates along every function input, "active" only
    along inputs fed by parameters that depend on the optimized values (enough for
    gradients with respect to `optimized_parameters`), "none" skips derivatives.
    """

    def __init__(self, groups, source, swept_columns, active_parameters):
        self.groups = []
        for function_index, input_indices in groups:
            varies = bool(np.isin(input_indices, swept_columns).any())
            width = input_indices.shape[1]
            slots = {
                "full": np.arange(width),
                "active": np.nonzero(np.isin(input_indices, active_parameters).any(axis=0))[0],
                "none": np.arange(0),
            }
            self.groups.append((kernel(FUNCTIONS[function_index], (width,)), input_indices, varies, slots))
        self.source = source
        self.sizes = [4 * len(group[1]) for group in self.groups]

    def forward(self, parameters: np.ndarray, mode: str):
        """Flattened outputs (R, sum 4 K_t) and per-group Jacobians along the mode's input slots."""
        rows = parameters.shape[0]
        outputs, jacobians = [], []
        for function_kernel, input_indices, varies, slots in self.groups:
            block = parameters if varies else parameters[:1]
            value, derivative = function_kernel(block[:, input_indices], slots[mode])
            outputs.append(np.broadcast_to(value.reshape(value.shape[0], -1), (rows, value.shape[1] * 4)))
            jacobians.append(derivative)
        return np.concatenate(outputs, axis=1), jacobians

    def backward(self, output_bar: np.ndarray, jacobians: list, parameters_bar: np.ndarray, mode: str):
        """Accumulate parameter cotangents (complex, R x P) from flattened output cotangents."""
        start = 0
        for (function_kernel, input_indices, varies, slots), derivative, size in zip(self.groups, jacobians, self.sizes):
            bar = output_bar[:, start:start + size].reshape(output_bar.shape[0], -1, 4)
            start += size
            columns = slots[mode]
            if len(columns) == 0:
                continue
            if not varies:
                bar = bar.sum(axis=0, keepdims=True)
            input_bar = np.einsum("rko,irko->rki", bar, derivative)  # (R', K, slots)
            row_index = np.arange(input_bar.shape[0])[:, None, None]
            np.add.at(parameters_bar, (row_index, input_indices[None][:, :, columns]), input_bar)


class HostEngine:
    """Forward and reverse pass of `simulate` in NumPy/SciPy for one `SimulationPlan`."""

    def __init__(self, plan):
        from differometor.build import LINKING_FUNCTIONS

        self.plan = plan
        swept = np.concatenate([plan.carrier_changing_parameter_indices, plan.signal_changing_parameter_indices])
        # Parameters that depend on the optimized values (directly or through linking).
        active = set(int(i) for i in plan.optimized_parameter_indices)
        changed = True
        while changed:
            changed = False
            for source, target in zip(plan.linked_indices, plan.indices_to_link):
                if int(source) in active and int(target) not in active:
                    active.add(int(target))
                    changed = True
        active = np.array(sorted(active), dtype=int)
        self.carrier = _Stage(plan.carrier_groups, plan.carrier_source, plan.carrier_changing_parameter_indices, active)
        self.signal = _Stage(plan.signal_groups, plan.signal_source, swept, active)
        self.noise = _Stage(plan.noise_groups, plan.noise_source, swept, active)
        self.linking = [kernel(lambda v, f=LINKING_FUNCTIONS[int(i)]: jnp.asarray(f(v[0]), jnp.float64).reshape(()), (1,))
                        for i in plan.linking_function_indices]
        self.cache: "OrderedDict[int, dict]" = OrderedDict()
        self.tokens = itertools.count(1)

    # -- forward -----------------------------------------------------------

    def forward(self, optimized, parameters, carrier_changing_values, signal_changing_values,
                carrier_matrix, signal_values, noise_values, noise_selection_vectors, mode: str):
        plan = self.plan
        state = {}
        p = np.real(np.asarray(parameters)[0]).astype(np.float64)
        p[plan.optimized_parameter_indices] = np.asarray(optimized, dtype=np.float64)[plan.optimized_value_indices]
        linked_in = p[plan.linked_indices].copy()
        jacobian = mode != "none"
        linked = [k(linked_in[j:j + 1], None if jacobian else ()) for j, k in enumerate(self.linking)]
        p[plan.indices_to_link] = [value for value, _ in linked]
        qhd = np.exp(1j * np.radians(p[plan.qhd_parameter_indices]))

        # Carrier (dense LAPACK solve, one system per carrier sweep row).
        carrier_parameters = _expand(p[None, :], plan.carrier_changing_parameter_indices, carrier_changing_values)
        carrier_out, carrier_jac = self.carrier.forward(carrier_parameters, mode)
        system = np.array(np.broadcast_to(carrier_matrix, (carrier_parameters.shape[0],) + np.shape(carrier_matrix)))
        system[:, plan.carrier_rows, plan.carrier_columns] = carrier_out[:, plan.carrier_source]
        carrier = np.linalg.solve(system[:, :, :-1], system[:, :, -1:])[..., 0]  # (Rc, Nc)

        # Signal system values on the sparse pattern.
        signal_parameters = _expand(carrier_parameters, plan.signal_changing_parameter_indices, signal_changing_values)
        rows = signal_parameters.shape[0]
        signal_out, signal_jac = self.signal.forward(signal_parameters, mode)
        values = np.array(np.broadcast_to(signal_values, (rows, len(signal_values))))
        values[:, plan.signal_update_positions] = signal_out[:, plan.signal_source]
        unscaled = values[:, plan.placing_positions].copy()
        values[:, plan.placing_positions] = -unscaled * carrier[:, plan.placing_sources]
        values[:, plan.conjugate_positions] = np.conj(values[:, plan.conjugate_positions])
        matrix_values = values[:, plan.a_positions]
        rhs = np.zeros((rows, plan.signal_size), dtype=np.complex128)
        rhs[:, plan.rhs_rows] = values[:, plan.rhs_positions]

        # Detector selection vectors with homodyne phases.
        c = plan.carrier_size
        base_selection = np.array(noise_selection_vectors, dtype=np.complex128)
        q = plan.qhd_placing
        unphased = base_selection[q[:, 0], q[:, 1], q[:, 2]].copy()
        base_selection[q[:, 0], q[:, 1], q[:, 2]] *= qhd
        tiled = np.tile(base_selection, (1, carrier.shape[0], 1))  # (D, Rc, N)
        selection = tiled.copy()
        selection[:, :, :c] = tiled[:, :, :c] * carrier
        selection[:, :, c:2 * c] = np.conj(tiled[:, :, c:2 * c] * carrier)
        selection_full = np.broadcast_to(selection, (selection.shape[0], rows, selection.shape[2]))

        # Sparse LU per frequency: signal and noise weights (one refinement step each).
        signal_system = SparseSystem(plan, matrix_values)
        x = signal_system.solve(rhs, "N")
        w = signal_system.solve(selection_full, "H")

        # Quantum noise: w^H M w.
        noise_out, noise_jac = self.noise.forward(signal_parameters, mode)
        noise_matrix = np.array(np.broadcast_to(noise_values, (rows, len(noise_values))))
        noise_matrix[:, plan.noise_update_positions] = noise_out[:, plan.noise_source]
        sources = np.zeros_like(w)
        np.add.at(sources, (slice(None), slice(None), plan.noise_rows), noise_matrix * w[:, :, plan.noise_columns])
        quadratic = np.sum(np.real(np.conj(w) * sources), axis=2)
        noise = np.sqrt(_NOISE_SCALE * quadratic)  # (D, F)

        outputs = (carrier.T.copy(), x.T.copy(), noise.reshape(plan.noise_output_shape))
        if jacobian:
            state.update(mode=mode, linked=linked, qhd=qhd, unphased=unphased, carrier_jac=carrier_jac, system=system,
                         carrier=carrier, signal_jac=signal_jac, unscaled=unscaled, signal_system=signal_system, x=x, w=w,
                         tiled=tiled, noise_jac=noise_jac, noise_matrix=noise_matrix, sources=sources,
                         noise=noise, rows=rows, carrier_rows=carrier_parameters.shape[0],
                         signal_count=np.shape(signal_changing_values)[1], parameter_count=len(p))
        return outputs, state

    # -- reverse -----------------------------------------------------------

    def backward(self, state, carrier_bar_t, signal_bar_t, noise_bar, signal_values_count, optimized_count):
        plan, s = self.plan, state
        rows, rc, c = s["rows"], s["carrier_rows"], plan.carrier_size
        carrier, x, w = s["carrier"], s["x"], s["w"]

        # noise = sqrt(k q),  q = Re(w^H M w)
        noise_bar = np.asarray(noise_bar, dtype=np.float64).reshape(s["noise"].shape)
        with np.errstate(divide="ignore", invalid="ignore"):
            q_bar = noise_bar * _NOISE_SCALE / (2 * s["noise"])
        q_bar = q_bar[:, :, None]
        w_bar = q_bar * np.conj(s["sources"])
        np.add.at(w_bar, (slice(None), slice(None), plan.noise_columns),
                  q_bar * np.conj(w[:, :, plan.noise_rows]) * s["noise_matrix"])
        noise_matrix_bar = np.sum(q_bar * np.conj(w[:, :, plan.noise_rows]) * w[:, :, plan.noise_columns], axis=0)

        # Linear block: x = A^-1 b, w = A^-H s.
        x_bar = np.asarray(signal_bar_t).T.astype(np.complex128)
        lam = s["signal_system"].solve(x_bar, "T")                     # A^-T x_bar
        mu = np.conj(s["signal_system"].solve(np.conj(w_bar), "N"))    # conj(A^-1 conj(w_bar))
        matrix_bar = -lam[:, plan.a_rows] * x[:, plan.a_columns] - np.sum(
            np.conj(w[:, :, plan.a_rows] * mu[:, :, plan.a_columns]), axis=0)

        values_bar = np.zeros((rows, signal_values_count), dtype=np.complex128)
        values_bar[:, plan.a_positions] = matrix_bar
        values_bar[:, plan.rhs_positions] = lam[:, plan.rhs_rows]
        values_bar[:, plan.conjugate_positions] = np.conj(values_bar[:, plan.conjugate_positions])

        carrier_bar = np.asarray(carrier_bar_t).T.astype(np.complex128)  # (Rc, Nc)
        scaled_bar = values_bar[:, plan.placing_positions]
        values_bar[:, plan.placing_positions] = -scaled_bar * carrier[:, plan.placing_sources]
        _add_rows(carrier_bar, plan.placing_sources, -scaled_bar * s["unscaled"])

        # Selection vectors: broadcast (D, Rc, N) -> (D, rows, N), Rc is 1 or rows.
        selection_bar = mu.copy() if rc == rows else mu.sum(axis=1, keepdims=True)
        tiled = s["tiled"]
        tiled_bar = selection_bar.copy()
        tiled_bar[:, :, :c] = selection_bar[:, :, :c] * carrier
        carrier_bar += np.sum(selection_bar[:, :, :c] * tiled[:, :, :c], axis=0)
        lower_bar = np.conj(selection_bar[:, :, c:2 * c])  # lower = conj(tiled * carrier)
        tiled_bar[:, :, c:2 * c] = lower_bar * carrier
        carrier_bar += np.sum(lower_bar * tiled[:, :, c:2 * c], axis=0)
        base_bar = tiled_bar.sum(axis=1, keepdims=True)  # (D, 1, N), undo the tile over Rc
        qp = plan.qhd_placing
        qhd_bar = base_bar[qp[:, 0], qp[:, 1], qp[:, 2]] * s["unphased"]
        selection_vectors_bar = base_bar.copy()
        selection_vectors_bar[qp[:, 0], qp[:, 1], qp[:, 2]] *= s["qhd"]

        # Signal and noise entries -> signal-stage parameters.
        signal_parameters_bar = np.zeros((rows, s["parameter_count"]), dtype=np.complex128)
        signal_out_bar = np.zeros((rows, sum(self.signal.sizes)), dtype=np.complex128)
        np.add.at(signal_out_bar, (slice(None), plan.signal_source), values_bar[:, plan.signal_update_positions])
        self.signal.backward(signal_out_bar, s["signal_jac"], signal_parameters_bar, s["mode"])
        noise_out_bar = np.zeros((rows, sum(self.noise.sizes)), dtype=np.complex128)
        np.add.at(noise_out_bar, (slice(None), plan.noise_source), noise_matrix_bar[:, plan.noise_update_positions])
        self.noise.backward(noise_out_bar, s["noise_jac"], signal_parameters_bar, s["mode"])

        signal_base_bar = values_bar.sum(axis=0)
        signal_base_bar[plan.signal_update_positions] = 0
        noise_base_bar = noise_matrix_bar.sum(axis=0)
        noise_base_bar[plan.noise_update_positions] = 0
        signal_changing_bar, carrier_parameters_bar = _expand_backward(
            signal_parameters_bar, plan.signal_changing_parameter_indices, s["signal_count"], rc)

        # Carrier: carrier = C^-1 d  (dense).
        system = s["system"]
        lam_c = np.linalg.solve(np.transpose(system[:, :, :-1], (0, 2, 1)), carrier_bar[..., None])[..., 0]
        system_bar = np.concatenate([-lam_c[:, :, None] * carrier[:, None, :], lam_c[:, :, None]], axis=2)
        carrier_out_bar = np.zeros((rc, sum(self.carrier.sizes)), dtype=np.complex128)
        np.add.at(carrier_out_bar, (slice(None), plan.carrier_source),
                  system_bar[:, plan.carrier_rows, plan.carrier_columns])
        self.carrier.backward(carrier_out_bar, s["carrier_jac"], carrier_parameters_bar, s["mode"])
        carrier_matrix_bar = system_bar.sum(axis=0)
        carrier_matrix_bar[plan.carrier_rows, plan.carrier_columns] = 0
        carrier_changing_bar, p_bar = _expand_backward(
            carrier_parameters_bar, plan.carrier_changing_parameter_indices, rc, 1)
        p_bar = p_bar[0]

        # Homodyne phases: qhd = exp(i radians(p)).
        np.add.at(p_bar, plan.qhd_parameter_indices, qhd_bar * 1j * np.pi / 180 * s["qhd"])

        # Linking: p[to_link] = f(p[linked]) (all inputs read before writing).
        link_bar = p_bar[plan.indices_to_link].copy()
        p_bar[plan.indices_to_link] = 0
        for j, (_, derivative) in enumerate(s["linked"]):
            p_bar[plan.linked_indices[j]] += link_bar[j] * derivative.reshape(-1)[0]

        # Optimized values.
        optimized_bar = np.zeros(optimized_count, dtype=np.float64)
        np.add.at(optimized_bar, plan.optimized_value_indices, np.real(p_bar[plan.optimized_parameter_indices]))
        p_bar[plan.optimized_parameter_indices] = 0

        return (optimized_bar, p_bar[None, :], carrier_changing_bar, signal_changing_bar,
                carrier_matrix_bar, signal_base_bar, noise_base_bar, selection_vectors_bar)

    # -- cache ---------------------------------------------------------------

    def remember(self, state) -> int:
        token = next(self.tokens)
        self.cache[token] = state
        while len(self.cache) > 2:
            self.cache.popitem(last=False)
        return token


def _expand(parameters: np.ndarray, indices: np.ndarray, values: np.ndarray) -> np.ndarray:
    """NumPy twin of `simulate.expand_parameters`: tile rows, write sweep values into the first rows."""
    values = np.real(np.asarray(values))
    count = values.shape[1]
    tiled = np.tile(parameters, (count, 1))
    tiled[np.arange(count)[:, None], indices[None, :]] = values.T
    return tiled


def _expand_backward(tiled_bar: np.ndarray, indices: np.ndarray, count: int, source_rows: int):
    """Reverse of `_expand`: (values_bar (V, count), parameters_bar (source_rows, P))."""
    rows = np.arange(count)[:, None]
    values_bar = tiled_bar[rows, indices[None, :]].T.copy()
    tiled_bar = tiled_bar.copy()
    tiled_bar[rows, indices[None, :]] = 0
    return values_bar, tiled_bar.reshape(count, source_rows, tiled_bar.shape[1]).sum(axis=0)


def _add_rows(target: np.ndarray, columns: np.ndarray, values: np.ndarray):
    """target (Rc, N) += values (R, K) scattered to `columns`, summing R onto Rc."""
    rc = target.shape[0]
    values = values.reshape(-1, rc, values.shape[1]).sum(axis=0)
    np.add.at(target, (slice(None), columns), values)


_GSTRF = None


def _superlu_gstrf():
    """
    SuperLU's factorization routine (`scipy.sparse.linalg._dsolve._superlu.gstrf`).

    `scipy.sparse.linalg.splu` is a thin wrapper around this compiled routine, but
    importing `scipy.sparse.linalg` loads the whole sparse linear-algebra stack
    (~0.12 s). The extension module only needs NumPy, so it is loaded directly
    (~4 ms). Falls back to `splu` if the module cannot be located.
    """
    global _GSTRF
    if _GSTRF is None:
        import importlib.util
        import os
        import sys

        name = "scipy.sparse.linalg._dsolve._superlu"
        try:
            module = sys.modules.get(name)
            if module is None:
                import scipy

                directory = os.path.join(os.path.dirname(scipy.__file__), "sparse", "linalg", "_dsolve")
                filename = next(f for f in os.listdir(directory)
                                if f.startswith("_superlu") and f.endswith((".so", ".pyd")))
                spec = importlib.util.spec_from_file_location(name, os.path.join(directory, filename))
                module = importlib.util.module_from_spec(spec)
                spec.loader.exec_module(module)
            _GSTRF = module.gstrf
        except Exception:  # pragma: no cover - unusual SciPy layout
            _GSTRF = False
    return _GSTRF


def _no_csc_construct(*args):  # L and U factors are never materialized
    raise NotImplementedError


# Small supernodes suit these ~3 non-zeros-per-row matrices (~20 % faster than the defaults).
_SUPERLU_OPTIONS = dict(DiagPivotThresh=None, ColPerm="COLAMD", PanelSize=1, Relax=1)


class SparseSystem:
    """
    The signal system of every frequency: SuperLU factors plus one step of iterative refinement.

    The signal systems are extremely badly scaled (condition number ~1e30), and a sparse
    LU's fill-reducing column order can cost accuracy compared with dense LU. One step of
    iterative refinement (x += A^-1 (b - A x), reusing the factors) recovers it: against
    the correctly rounded solution (extended-precision refinement) the refined sparse
    solve stays within ~1e-9 in log sensitivity, and is considerably closer than the
    original dense solver on the setups where that one loses accuracy
    (scripts/roundoff_study.py, scripts/check_setups.py).
    """

    def __init__(self, plan, values: np.ndarray):
        self.plan = plan
        self.values = values  # (F, nnz), CSC order
        self.factors = _factorize(plan, values)

    def matvec(self, x: np.ndarray, trans: str) -> np.ndarray:
        """A x, A^T x or A^H x for every frequency; x has shape (..., F, N)."""
        plan, n = self.plan, self.plan.signal_size
        values = np.conj(self.values) if trans == "H" else self.values
        out_index, in_index = (plan.a_rows, plan.a_columns) if trans == "N" else (plan.a_columns, plan.a_rows)
        products = values * x[..., in_index]  # (..., F, nnz)
        flat = products.reshape(-1, products.shape[-1])
        bins = (np.arange(flat.shape[0])[:, None] * n + out_index[None, :]).ravel()
        size = flat.shape[0] * n
        result = np.bincount(bins, weights=flat.real.ravel(), minlength=size) \
            + 1j * np.bincount(bins, weights=flat.imag.ravel(), minlength=size)
        return result.reshape(x.shape)

    def _solve_once(self, rhs: np.ndarray, trans: str) -> np.ndarray:
        out = np.empty(rhs.shape, dtype=np.complex128)
        for index, lu in enumerate(self.factors):
            block = rhs[..., index, :]  # (N,) or (D, N)
            if lu is None:  # singular or non-finite matrix: NaN, like a dense LAPACK solve would give
                out[..., index, :] = np.nan
            elif block.ndim == 1:
                out[index] = lu.solve(np.ascontiguousarray(block), trans=trans)
            else:
                out[..., index, :] = lu.solve(np.ascontiguousarray(block.T), trans=trans).T
        return out

    def solve(self, rhs: np.ndarray, trans: str = "N") -> np.ndarray:
        """Solve A x = rhs (trans "N"), A^T x = rhs ("T") or A^H x = rhs ("H"); rhs is (..., F, N)."""
        rhs = np.asarray(rhs, dtype=np.complex128)
        x = self._solve_once(rhs, trans)
        return x + self._solve_once(rhs - self.matvec(x, trans), trans)


def _factorize(plan, values: np.ndarray) -> list:
    """SuperLU factorization (COLAMD ordering, partial pivoting) per frequency on the plan's CSC pattern."""
    n = plan.signal_size
    gstrf = _superlu_gstrf()
    if gstrf:
        indices = plan.a_rows.astype(np.intc)
        indptr = plan.a_indptr.astype(np.intc)
        nnz = len(indices)

        def factor(row):
            return gstrf(n, nnz, np.ascontiguousarray(row, dtype=np.complex128), indices, indptr,
                         csc_construct_func=_no_csc_construct, ilu=False, options=dict(_SUPERLU_OPTIONS))
    else:
        from scipy.sparse import csc_matrix
        from scipy.sparse.linalg import splu

        def factor(row):
            return splu(csc_matrix((row, plan.a_rows, plan.a_indptr), shape=(n, n)), permc_spec="COLAMD")

    factors = []
    for row in values:
        try:
            factors.append(factor(row) if np.isfinite(row).all() else None)
        except RuntimeError:  # exactly singular: propagate NaN instead of raising
            factors.append(None)
    return factors


