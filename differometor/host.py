"""
Host (NumPy) execution engine with JAX-derived derivatives.

Why
---
For the public setup, XLA spends far longer *compiling* the simulation (~20 s for
the forward and reverse passes) than running it. The expensive part to compile
is the component physics: a few hundred elementwise transcendental operations,
each code-generated by LLVM. Executing the same operations with NumPy needs no
compilation at all and takes milliseconds.

How
---
* **Physics is traced from JAX; tangent rules are implemented here.** Each
  component function in `components.py` is traced once into a primal jaxpr
  (without XLA compilation). `_jvp_jaxpr` evaluates that program and the
  primitive tangent rules below with NumPy, batched over matrix entries and
  frequencies. Custom derivative calls are rejected so their declared rules
  are not silently replaced by differentiation of the primal body.
* **Linear algebra on the host.** The small carrier system uses LAPACK through
  NumPy. The sparse signal system uses SuperLU, one factorization per frequency,
  shared by the signal solve and the quantum-noise solve.
* **Adjoint method for the reverse pass.** The reverse pass walks the same steps
  backwards by hand (`HostEngine.backward`), reusing the forward pass's LU
  factors and entry Jacobians.
* **One JAX primitive.** `make_host_simulate` wraps forward and reverse pass in a
  `jax.custom_vjp` around `jax.pure_callback`, so the simulation still works
  under `jax.jit`, `jax.vjp` and `jax.grad`, while XLA compiles only two callbacks.
"""

