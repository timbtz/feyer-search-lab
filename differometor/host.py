def make_host_simulate(plan):
    """`jax.custom_vjp` simulate for one plan, running forward and reverse pass on the host."""
    engine = HostEngine(plan)

    def output_specs(carrier_matrix, signal_changing_values, carrier_changing_values):
        rc = carrier_changing_values.shape[1]
        rows = rc * signal_changing_values.shape[1]
        return (jax.ShapeDtypeStruct((carrier_matrix.shape[0], rc), jnp.complex128),
                jax.ShapeDtypeStruct((plan.signal_size, rows), jnp.complex128),
                jax.ShapeDtypeStruct(plan.noise_output_shape, jnp.float64))

    modes = ("none", "active", "full")

    def run_forward(args, mode):
        def host(*arrays):
            outputs, state = engine.forward(*arrays, mode=mode)
            # The token encodes the cache slot and the Jacobian mode (for recomputation).
            token = engine.remember(state) * len(modes) + modes.index(mode) if mode != "none" else 0
            return outputs + (np.asarray(token, dtype=np.int64),)
        _, parameters, cvals, svals, cmat, *_ = args
        specs = output_specs(cmat, svals, cvals) + (jax.ShapeDtypeStruct((), jnp.int64),)
        return jax.pure_callback(host, specs, *args, vmap_method="sequential")

    @jax.custom_vjp
    def simulate(*args):
        *outputs, _ = run_forward(args, "none")
        return tuple(outputs)

    def forward(*args):
        # symbolic_zeros=True: each argument says whether it is being differentiated.
        values = tuple(arg.value for arg in args)
        only_optimized = not any(arg.perturbed for arg in args[1:])
        *outputs, token = run_forward(values, "active" if only_optimized else "full")
        return tuple(outputs), (token, values)

    def backward(residuals, cotangents):
        from jax.custom_derivatives import SymbolicZero

        token, args = residuals
        cotangents = tuple(jnp.zeros(c.aval.shape, c.aval.dtype) if isinstance(c, SymbolicZero) else c
                           for c in cotangents)

        def host(token, carrier_bar, signal_bar, noise_bar, *arrays):
            slot, mode = divmod(int(token), len(modes))
            state = engine.cache.get(slot)
            if state is None:  # state evicted: recompute the forward pass
                _, state = engine.forward(*arrays, mode=modes[mode])
            bars = engine.backward(state, carrier_bar, signal_bar, noise_bar, len(arrays[5]), len(arrays[0]))
            converted = []
            for bar, array in zip(bars, arrays):
                array = np.asarray(array)
                bar = np.asarray(bar)
                if not np.iscomplexobj(array):
                    bar = np.real(bar)
                converted.append(bar.astype(array.dtype).reshape(array.shape))
            return tuple(converted)

        specs = tuple(jax.ShapeDtypeStruct(jnp.shape(a), jnp.result_type(a)) for a in args)
        return jax.pure_callback(host, specs, token, *cotangents, *args, vmap_method="sequential")

    simulate.defvjp(forward, backward, symbolic_zeros=True)
    return simulate
