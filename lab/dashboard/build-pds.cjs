// Reproduce the pinned, unmodified PDS stylesheet and loader assets.
const fs = require('node:fs');
const path = require('node:path');
const root = __dirname;
const pkg = path.dirname(require.resolve('@porsche-design-system/components-js/package.json'));
const version = require(path.join(pkg, 'package.json')).version;
if (version !== '4.10.1') throw new Error('Expected reviewed PDS version 4.10.1');
for (const name of ['variables','normalize','font-face']) fs.copyFileSync(path.join(pkg,`stylesheets/${name}.css`),path.join(root,`pds-${name}.css`));
const html = require('@porsche-design-system/components-js/partials').getLoaderScript();
const match = html.match(/^<script[^>]*>([\s\S]*)<\/script>$/);
if (!match) throw new Error('Unexpected PDS loader format');
fs.writeFileSync(path.join(root,'pds-loader.js'),`/* Porsche Design System ${version}; generated by build-pds.cjs. */\n${match[1]}\n`);
fs.copyFileSync(path.join(pkg,'LICENSE.md'),path.join(root,'PDS-LICENSE.md'));
fs.copyFileSync(path.join(pkg,'OSS_NOTICE'),path.join(root,'PDS-OSS-NOTICE'));
